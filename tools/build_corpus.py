#!/usr/bin/env python3
"""Builds the on-device corpus (raw messages only) from the message fixtures in the shared engine's tests.

Each entry is (sender, body). Labels are NOT stored here: the app labels each message with the verified rule reader at
start-up (Corpus.kt), so a label is always what the current rules say. Source label for every entry:
"reconstructed test fixture (verified rule reading)". Run from the repo root:  python3 tools/build_corpus.py
"""
import glob, re, sys

ROOT = "shared/src/commonTest/kotlin/com/uaefinancial/tracker"
SKIP = ("StatementFixtures", "RealStatement", "StatementReader", "StatementImport", "CandidateScreenTest", "IntelTest")
lit = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
pair = re.compile(r'\(\s*"([^"\n]{2,40})"\s*,\s*((?:"(?:[^"\\\n]|\\.)*"\s*\+?\s*)+)')
chain = re.compile(r'((?:"(?:[^"\\\n]|\\.)*"\s*\+\s*)*"(?:[^"\\\n]|\\.)*")')
money = re.compile(r'\b(?:AED|USD|PKR|INR|SAR|QAR|KWD|OMR|BHD|EUR|GBP|Dhs|Rs)\b|\$')

def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            if n == 'n': out.append('\n'); i += 2; continue
            if n == 't': out.append('\t'); i += 2; continue
            if n == 'u' and i + 5 < len(s) + 0:
                try: out.append(chr(int(s[i + 2:i + 6], 16))); i += 6; continue
                except ValueError: pass
            out.append(n); i += 2; continue
        out.append(c); i += 1
    return ''.join(out)

def join(expr):
    return unescape(''.join(lit.findall(expr)))

found = {}
for f in sorted(glob.glob(ROOT + "/**/*.kt", recursive=True)):
    if any(k in f for k in SKIP):
        continue
    s = open(f, encoding="utf-8").read()
    for m in pair.finditer(s):
        body = join(m.group(2))
        if len(body) > 35 and re.search(r'\d', body) and money.search(body):
            found.setdefault(body, m.group(1))
    for m in chain.finditer(s):
        body = join(m.group(1))
        if len(body) > 45 and re.search(r'\d', body) and money.search(body):
            found.setdefault(body, "")

def esc(b):
    return ('"' + b.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$')
            .replace('\n', '\\n').replace('\r', '').replace('\t', '\\t') + '"')

found = {b: snd for b, snd in found.items() if '${' not in b and '$' not in snd and len(snd) <= 30}
rows = sorted(found.items(), key=lambda kv: (kv[1], kv[0]))
out = ["package com.uaefinancial.tracker.intel", "",
       "// GENERATED by tools/build_corpus.py from the message fixtures in the engine's tests. Do not edit by hand.",
       "// Source label for every entry: reconstructed test fixture (labelled by the verified rule reader at start-up).",
       "// Only raw wording of test messages (invented numbers); nothing from a real user.", "",
       "internal object CorpusData {", "    /** (sender, body); sender is empty when the fixture does not name one. */",
       "    val raw: List<Pair<String, String>> = listOf("]
for sender, body in rows:
    out.append(f"        {esc(sender)} to {esc(body)},")
out += ["    )", "}", ""]
open("shared/src/commonMain/kotlin/com/uaefinancial/tracker/intel/CorpusData.kt", "w", encoding="utf-8").write("\n".join(out))
print(len(rows), "messages;", sum(1 for _, s in rows if s), "with a sender")
